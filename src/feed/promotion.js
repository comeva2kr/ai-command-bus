// 승격 제외 — 피드에는 두되, 우리 이름으로 발행하는 자리에는 올리지 않는다.
//
// ── 왜 (2026-08-04 적대적 검수 3인)
// 자체 콘텐츠 페이지의 대표 글로 이런 것들이 올라와 있었다:
//   "300추 가능한가요?"                    → 브리핑 6대 이슈 3위
//   "실시간 세르카 나메 2관 파티모집창"      → 화제 랭킹 2위
// 둘 다 그 커뮤니티 안에서는 반응이 크지만 **바깥 사람에게는 읽을 것이 없다.**
// 이런 글이 대표 자리에 있으면 심사관에게는 "콘텐츠가 지나치게 부족하여
// 유의미한 소비가 발생하지 않는 매체"로 읽히고, 처음 온 사람에게는 그냥
// 이상한 사이트로 읽힌다.
//
// ── 원칙: 삭제가 아니라 승격 제외
// David의 지시는 일관되게 "삭제 금지, 태그 후 게이트"다. 커뮤니티에서 반응이
// 컸다는 사실 자체는 데이터이므로 **피드에서는 그대로 보인다.** 다만
// 브리핑·랭킹처럼 우리가 "오늘의 대표"라고 이름 붙이는 자리에는 올리지 않는다.
// 트래픽 손실 0, 리스크만 제거하는 경로다.
//
// ── 원칙: 못 하는 것은 하는 척하지 않는다
// 검수는 "청계천에서 흡연하는 중국인", "여경 불안하다고 말하는 남자들…" 같은
// 국적·성별 갈등 유발 제목도 지적했다. 그런데 이건 **정규식으로 판별할 수
// 없다.** "중국인"이 들어갔다고 막으면 정상 뉴스가 통째로 죽고, 안 막으면
// 그대로 나간다. 어설픈 의미 판별은 오탐으로 피드를 망가뜨린다.
//
// 그래서 두 층으로 나눈다:
//   lowValue  — **형식**으로 판별 가능한 것만. 추천 구걸·모집글 등.
//               랭킹·브리핑 대표 자리에서 제외한다.
//   adUnsafe  — 광고를 **바로 옆에** 붙이지 않을 것. 비속어·성인·정치/종교처럼
//               이미 태그가 붙어 있는 신호만 쓴다. 여기서도 글을 지우지 않는다.
//
// 의미 판별이 필요한 영역(혐오·차별)은 규칙이 아니라 사람이나 모델의 판단이
// 필요하다 — 지금 없는 것을 있는 척하지 않고, 대신 그 글 옆에 광고를 두지
// 않는 것으로 실제 리스크(광고주 브랜드 안전)만 막는다.
import { hasProfanity } from "./profanity.js";

// 형식으로 판별되는 저가치 패턴. 각 항목은 "왜 이게 바깥 사람에게 읽을 것이
// 없는가"로 설명될 수 있어야 한다. 애매하면 넣지 않는다 — 오탐 하나가
// 정상 글을 대표 자리에서 밀어낸다.
export const LOW_VALUE_PATTERNS = [
  // 추천 구걸: 글 내용이 아니라 그 게시판의 추천 수치 자체가 목적인 글
  { re: /\d+\s*추\s*(가능|가나|가즈|고고|채워|모아|찍)/, why: "추천 구걸" },
  { re: /추천\s*(좀|한번|부탁)\s*(해|주|드)/, why: "추천 구걸" },
  // 모집: 그 커뮤니티 이용자만 참여할 수 있는 공지
  { re: /(파티|길드|클랜|공대|스터디|팀원|인원)\s*모집/, why: "모집 공고" },
  { re: /모집\s*(창|글|합니다|중)/, why: "모집 공고" },
  // 출석·인증 놀이: 반응은 크지만 읽을 내용이 없다
  { re: /^(출석|출첵|인증)\s*/, why: "출석·인증" },
  // 테스트·삭제 예정 글
  { re: /^(테스트|test)\s*\d*$/i, why: "테스트 글" },
  // 경품 참여 유도와 보도자료형 판촉은 실시간 피드에는 남기되, 지금핫이 고른
  // 대표 이슈로 승격하지 않는다. 실제 07시 판본에서 예술·기술 최소 칸을 채우며
  // 핵심 소식처럼 노출된 제목만 좁게 고정한다.
  { re: /(댓글|사연).{0,40}(남기|작성).{0,40}(받아가|증정|추첨)/, why: "경품 참여 유도" },
  { re: /(?:특별\s*)?프로모션\s*(?:진행|실시|개최)\s*$/i, why: "상업 판촉문" },
  // 커뮤니티 반응이 커도 가격을 전면에 둔 월간 특가 글은 상품 광고다. 월 숫자
  // 또는 제목 첫머리의 "특가"와 실제 가격·할인 신호가 함께 있을 때만 막는다.
  { re: /^(?:\d{1,2}월\s*)?특가[\s):].{0,80}(?:\d[\d,]*(?:원|%|만원)|무료|할인|증정|쿠폰)/i, why: "가격형 특가 광고" },
  // 기업명이 주어이고 대회 현장 물품 제공량이 결론인 좁은 협찬 보도. 재난
  // 구호처럼 공공성이 있는 "생수 지원"까지 막지 않도록 경기 문맥을 요구한다.
  { re: /^[^,]{2,30},.{0,45}(?:대회|경기|봉황대기).{0,30}(?:음료|생수|간식|물품)\s*[\d,만천]+\s*개?\s*(?:지원|제공)$/i, why: "기업 행사 협찬 보도" },
  // 하루특가류 판매 라벨: 3일 관찰(11슬롯, 제목 10,020종)에서 이 계열 광고
  // 47건이 게이트를 전부 통과했고 3건이 유머판에 실선별됐다(예: "하루특가)
  // 유니맥스 벅스 킬러…" 아침판 2위). 위의 "가격형 특가 광고"는 제목 첫머리
  // "특가"만 보고, isDeal은 가격 표기를 요구해 "하루특가) 상품명, 규격, 수량"
  // 꼴이 둘 다 비켜 갔다. 실측된 접두 라벨만 잡는다 — "하루특가)"·"26년 첫출하
  // 특가)"·"[특가]"·"[선착코드특가]"·"[오늘의 특가]"처럼 짧은 수식어 뒤 "특가"가
  // 닫는 괄호로 끝나는 판매 말머리. 문장 속 "특가"("특가 논란", "반값 특가
  // 경쟁")는 괄호로 안 닫히므로 걸리지 않는다.
  { re: /^[\[(]?[^\[\]()]{0,12}특가\s*[)\]]/, why: "특가 라벨 광고" },
  // 같은 관찰의 딜 게시판 변형: "지센 여름 원피스 특가 (29,900원~/무료)" —
  // "특가" 직후 괄호 안 가격. 가격을 전면에 둔 판매 글만 좁게 잡는다.
  { re: /특가\s*\(\s*[\d,]+\s*원/, why: "특가 가격 병기 광고" }
];

// 우리 이름으로 "오늘의 대표"라고 붙이기엔 부적합한 표현.
//
// 앞의 주석에서 "의미 판별은 정규식으로 못 한다"고 했고 그건 여전히 맞다 —
// 국적·성별 갈등은 문맥이라 못 잡는다. 하지만 **표현 자체가 저속한 것**은
// 형식으로 잡힌다. 실측(2026-08-04): 검수 3인이 전원 지적한
//   "우리나라 못생남 빨아주느라 단어가 점점 하타치가 됨"
// 이 고친 뒤에도 브리핑 1위였다. 해설을 붙이려던 모델조차 그 이슈만
// 건너뛰었다(5/6) — 사람이 봐도 대표로 내세울 글이 아니라는 뜻이다.
//
// 마스킹 사전(profanity.js)과 분리한 이유: 저기 넣으면 피드 화면의 제목까지
// ●로 바뀐다. 여기 것은 **대표 자리에서만** 빼고 피드에는 원문 그대로 남긴다.
// 애드핏 정책의 "성적 비하 / 혐오" 조항에 걸리는 것을 우리 지면에서만 막는다.
//
// 일반어와 겹치는 것은 넣지 않는다 — 오탐 하나가 진짜 화제를 대표에서 밀어낸다.
// 짧은 말이 다른 단어에 묻히면 오탐이 난다 — 내 테스트가 실제로 잡았다:
// "일베이스캠프 등반기"가 "일베"에 걸렸다. 그래서 단어 경계를 함께 본다.
// 한국어는 조사가 붙으므로 뒤쪽은 느슨하게, 앞쪽은 다른 음절이 붙지 않도록.
export const UNPROMOTABLE_EXPRESSIONS = [
  { re: /빨아(주|준|댄)/, why: "성적 비하 표현" },
  { re: /못생(남|녀)/, why: "외모 비하" },       // 일상어 "못생겼다"는 넣지 않는다
  { re: /(김치녀|한남충|된장녀|맘충)/, why: "성별 비하 호칭" },
  // "일베이스캠프"가 "일베" + 조사 "이"로 읽혀 걸렸다(내 첫 시도의 오탐).
  // 조사를 경계로 인정하면 이런 합성어를 못 가른다. 그래서 **뒤에 한글이
  // 이어지면 다른 낱말로 본다** — 조사는 한 글자 뒤에 공백·문장부호가 온다.
  { re: /(^|[^가-힣])(일베|메갈)(?![가-힣])/, why: "극단 커뮤니티 지칭" },
  { re: /(^|[^가-힣])(일베|메갈)(의|는|가|를|에|와|과|도)(?![가-힣])/, why: "극단 커뮤니티 지칭" },
  { re: /(성매매|몰카|불법촬영)/, why: "범죄 소재" }
];

export function unpromotableReason(title) {
  const t = String(title || "");
  for (const { re, why } of UNPROMOTABLE_EXPRESSIONS) if (re.test(t)) return why;
  return null;
}
export const hasUnpromotableExpression = (title) => unpromotableReason(title) !== null;

// 제목이 저가치 형식인가. 이유를 함께 돌려준다 — 관리자 화면에서 "왜 빠졌나"를
// 볼 수 있어야 규칙을 고칠 수 있다.
export function lowValueReason(title) {
  const t = String(title || "").trim();
  if (!t) return "제목 없음";
  // 사실상 비어 있는 제목만 막는다. 한국어는 짧아도 내용이 있다 —
  // "尹 구속"(5자)처럼 5자짜리 진짜 뉴스가 있으므로 기준을 6자로 잡으면
  // 정상 글이 대표 자리에서 밀려난다. 오탐 하나가 진짜 화제를 죽인다.
  if (t.length < 3) return "제목이 사실상 비어 있다";
  for (const { re, why } of LOW_VALUE_PATTERNS) if (re.test(t)) return why;
  return null;
}

export const isLowValue = (title) => lowValueReason(title) !== null;

// 이 글 **옆에** 광고를 붙여도 되는가. 글 자체를 막는 게 아니다.
// 이미 붙어 있는 태그만 쓴다 — 새로 의미를 판별하려 들지 않는다.
export function adUnsafe(item) {
  if (!item) return false;
  const topics = Array.isArray(item.topics) ? item.topics : [];
  if (topics.includes("politics") || topics.includes("religion")) return true;
  // **분류(category)도 본다.** topics는 토픽 사전이 붙여 주는 값이라 못 붙는
  // 글이 있는데, 분류기가 politics로 넣은 글은 그 자체로 정치 글이다.
  // 사용자 단위 광고 차단을 걷어내면서(engine.getFeed) 이 검사가 유일한
  // 방어선이 되었으므로, 틈을 남기면 안 된다(2026-08-06).
  if (item.category === "politics" || item.category === "religion") return true;
  if (hasProfanity(item.title)) return true;
  return false;
}

// 우리 이름으로 발행하는 자리(브리핑·랭킹 대표)에 올려도 되는가.
export function promotable(item) {
  if (!item) return false;
  if (hasProfanity(item.title)) return false;
  if (hasUnpromotableExpression(item.title)) return false;
  if (isLowValue(item.title)) return false;
  return true;
}
