// 팝업에 내보낼 최신 소식 하나. 목록 전체를 보내지 않는 이유는, 팝업에서
// 사용자가 볼 것은 "이번에 뭐가 바뀌었나" 하나뿐이기 때문이다. 지난 소식은
// 아래 releaseHistoryHtml()로 서비스 소개에 나간다.
export function latestRelease() {
  return RELEASES[0] || null;
}

// 서비스 소개(/about#updates)에 넣는 전체 내역. "그때 뭐가 바뀌었더라"는
// 팝업이 지나간 뒤에도 찾아볼 수 있어야 한다. 서버가 about.html의
// <!-- NOWHOT_RELEASE_HISTORY --> 자리에 이 문자열을 끼운다. 목록을 HTML에
// 따로 베껴 두면 여기와 어긋나므로 원본은 RELEASES 하나뿐이다.
// 브라우저 기본 details/summary라 스크립트가 없고, 최신 항목만 펼쳐 둔다.
// 버전 표시는 따로 만들지 않고 id를 그대로 쓴다(빌드 해시를 안 쓰는 이유는 위와 같다).
function esc(s) {
  return String(s).replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
}

export function releaseHistoryHtml() {
  return RELEASES.map((r, i) =>
    `<details class="release"${i === 0 ? " open" : ""}>` +
    `<summary><time datetime="${esc(r.date)}">${esc(r.date)}</time>` +
    `<span class="release-title">${esc(r.title)}</span>` +
    `<span class="release-id">버전 ${esc(r.id)}</span></summary>` +
    `<ul>${(r.items || []).map((t) => `<li>${esc(t)}</li>`).join("")}</ul>` +
    `</details>`
  ).join("\n");
}
