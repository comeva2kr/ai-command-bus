// 왜 필요한가: 애드핏 매체심사가 2026-07-31 보류되면서 자체 콘텐츠 보강을
// 요구했고, 그 답으로 만든 것이 /briefing 이다. 그런데 2026-08-02 적대적 검수
// 실측에서 그 대표 페이지에 "개좆"이 마스킹 없이 3회 노출돼 있었고, 그중 2회는
// 커뮤니티 원문 인용이 아니라 **사이트가 직접 쓴 서술문**(섹션 대표 문장,
// '오늘의 논쟁') 안이었다. 심사원이 가장 먼저 열어보는 페이지다.
//
// 적용 범위를 좁게 잡는다:
//   - 피드 카드는 건드리지 않는다. 커뮤니티 글의 말투는 그 커뮤니티의 것이고,
//     원문을 임의로 고치면 큐레이션이 아니라 왜곡이다.
//   - 브리핑·랭킹처럼 **우리 이름으로 발행하는 페이지**에서만 마스킹한다.
//   - 대표 문장·'오늘의 논쟁'처럼 우리가 문장을 쓰는 자리는 마스킹이 아니라
//     아예 다른 글을 고른다(hasProfanity로 선정에서 제외).
//
// 사전은 설명 가능해야 한다 — 오탐이 나오면 매칭 로직을 꼬지 말고 단어를 빼라.
// 일반어와 겹치는 것은 애초에 넣지 않는다:
//   "새끼"  — "강아지 새끼", "새끼손가락"이 일상어다
//   "지랄"  — 경계선이지만 "지랄발광" 같은 관용 표현이 뉴스 인용에도 나온다
//   "존나"  — 넣었다. 일반어와 겹치지 않고 심사 관점에서 명백하다
export const PROFANITY = [
  "씨발", "시발", "씨봉", "씹할", "좆", "존나", "졸라씨", "병신", "썅",
  "개새끼", "개년", "개놈", "미친놈", "미친년", "닥쳐", "꺼져라",
  "엿먹", "지랄발광", "ㅅㅂ", "ㅄ", "ㅈ같"
];

// 마스킹은 첫 글자만 남기고 나머지를 ●로 — 무엇이 걸렸는지 사람은 알아보되
// 화면에는 원형이 남지 않는다. 완전히 지우면 문장이 끊겨 더 이상해진다.
function maskWord(w) {
  if (w.length <= 1) return "●";
  return w[0] + "●".repeat(w.length - 1);
}

export function hasProfanity(text) {
  const t = String(text || "");
  if (!t) return false;
  return PROFANITY.some((w) => t.includes(w));
}

export function maskProfanity(text) {
  let t = String(text || "");
  if (!t) return t;
  for (const w of PROFANITY) {
    if (!t.includes(w)) continue;
    t = t.split(w).join(maskWord(w));
  }
  return t;
}
