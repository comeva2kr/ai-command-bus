// 슬롯 태깅 — 어느 자리가 실제로 돈이 되는지 구분한다.
//
// 쿠팡 대시보드는 '페이지 키' 단위로만 실적을 쪼개서, 지면이 여럿이어도
// 전부 한 덩어리로 보였다. subId를 붙이면 슬롯별로 갈린다.
//
// 실측(2026-08-03): link.coupang.com/a/<code>?subId=feed 를 따라가면 최종
// 랜딩 URL에 subid=feed 로 그대로 실려 나가고, 수수료 태그(lptag)도 유지된다.
// 즉 링크를 깨지 않고 측정만 얻는다. 측정이 없으면 최적화도 없다.
export function withSubId(href, slot) {
  if (!href || !slot) return href;
  return href + (href.includes("?") ? "&" : "?") + "subId=" + encodeURIComponent(slot);
}
